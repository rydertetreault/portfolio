/**
 * Generate the ASCII hands for the homepage intro.
 *
 * Source: handofgod.png (the full Creation-of-Adam hands composition).
 * Outputs src/components/hand-ascii.ts with:
 *   LEFT_HAND   — God's hand (left half, fingertip at the right edge)
 *   RIGHT_HAND  — Adam's hand (right half, fingertip at the left edge)
 *
 * Character density / ramp / contrast match the original hand.jpg render
 * (~10 px per column, ~14.5 px per row at 1920 wide), but the crop covers the
 * whole hands so nothing is chopped at the bottom.
 */

import sharp from "sharp";
import { writeFileSync } from "fs";

const SRC = "handofgod.png";
const RAMP = " .·:;+=*x#%@";

// Crop out the border line on the right (x>=733) and the watermark bottom-left (y>=362).
const CROP = { left: 0, top: 48, width: 732, height: 292 };
const HAND_COLS = 200;
const CELL_ASPECT = 1.44; // px-per-row / px-per-col of the original render
const HAND_ROWS = Math.round((CROP.height / CROP.width) * HAND_COLS / CELL_ASPECT);

const buf = await sharp(SRC)
  .extract(CROP)
  .normalize()
  .linear(1.25, -4)
  .grayscale()
  .resize(HAND_COLS, HAND_ROWS, { fit: "fill" })
  .raw()
  .toBuffer();

// Local fill for God's index finger: at this character density its interior
// comes out too sparse. Lift ONLY the mid-tones (the dim interior dots) inside
// a feathered band that follows the finger's diagonal, leaving edges and
// background untouched.
const FINGER = { r0: 13, r1: 30, colAt: (r) => 70 + (r - 13) * 1.1, width: 26, feather: 3, lift: 80 };
const fingerWeight = (c, r) => {
  const fy = Math.min(1, Math.max(0, Math.min(r - FINGER.r0, FINGER.r1 - r) / FINGER.feather + 1));
  const c0 = FINGER.colAt(r), c1 = c0 + FINGER.width;
  const fx = Math.min(1, Math.max(0, Math.min(c - c0, c1 - c) / FINGER.feather + 1));
  return fx * fy;
};

const lines = [];
for (let r = 0; r < HAND_ROWS; r++) {
  let line = "";
  for (let c = 0; c < HAND_COLS; c++) {
    let v = buf[r * HAND_COLS + c];
    const w = fingerWeight(c, r);
    if (w > 0 && v > 10 && v < 150) v = Math.min(255, v + FINGER.lift * w); // mid-tones only
    line += RAMP[Math.round((v / 255) * (RAMP.length - 1))];
  }
  lines.push(line);
}

// Split at the middle of the empty gap between the fingertips.
const ink = new Array(HAND_COLS).fill(0);
for (const l of lines) for (let c = 0; c < HAND_COLS; c++) if (l[c] !== " ") ink[c]++;
let bestStart = 0, bestLen = 0, run = 0;
for (let c = Math.floor(HAND_COLS * 0.3); c < Math.floor(HAND_COLS * 0.8); c++) {
  if (ink[c] === 0) { run++; if (run > bestLen) { bestLen = run; bestStart = c - run + 1; } } else run = 0;
}
const SPLIT_COL = bestStart + Math.floor(bestLen / 2);

// Trim fully blank rows top/bottom (keep both halves on the same row grid).
let top = 0, bottom = lines.length;
while (top < bottom && lines[top].trim() === "") top++;
while (bottom > top && lines[bottom - 1].trim() === "") bottom--;
const rows = lines.slice(top, bottom);

const leftHand = rows.map((l) => l.slice(0, SPLIT_COL));
const rightHand = rows.map((l) => l.slice(SPLIT_COL));

const module = `// AUTO-GENERATED by scripts/generate-hand-ascii.mjs
// Source: handofgod.png — do not edit by hand; re-run the generator.

/* Left hand of the composition (God's hand reaching right).
   Fingertip is near the right edge (column ${SPLIT_COL - 1}). */
export const LEFT_HAND = ${JSON.stringify(leftHand.join("\n"))};

/* Right hand of the composition (Adam's hand reaching left).
   Fingertip is near the left edge. */
export const RIGHT_HAND = ${JSON.stringify(rightHand.join("\n"))};
`;

writeFileSync("src/components/hand-ascii.ts", module);
console.log(`Wrote src/components/hand-ascii.ts`);
console.log(`  LEFT_HAND   ${leftHand.length} rows × ${leftHand[0].length} cols`);
console.log(`  RIGHT_HAND  ${rightHand.length} rows × ${rightHand[0].length} cols`);
console.log(`  gap cols ${bestStart}-${bestStart + bestLen - 1}, split ${SPLIT_COL}`);
